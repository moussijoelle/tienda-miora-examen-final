BEGIN;

DROP TABLE IF EXISTS detalle_factura;
DROP TABLE IF EXISTS facturas;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS categorias;
DROP TABLE IF EXISTS clientes;

CREATE TABLE clientes (
  pk_cliente uuid PRIMARY KEY, -- numero unico UUID del cliente
  email text NOT NULL UNIQUE, -- correo, obligatorio (no puede quedar vacio), no se puede repetir
  tipo text NOT NULL CHECK (tipo IN ('empresa', 'autonomo')), -- empresa o autonomo, obligatorio
  razon_social text, -- si autonomo: el nombre de la persona
  nombres_cliente text NOT NULL, -- nombre, obligatorio
  apellido1_cliente text NOT NULL, -- primer apellido, obligatorio
  apellido2_cliente text, -- segundo apellido, opcional
  telefono_movil text, -- telefono movil
  rol text NOT NULL CHECK (rol IN ('cliente', 'administrador')), -- cliente o administrador, obligatorio
  fecha_registro timestamptz NOT NULL DEFAULT now(), -- fecha de alta, obligatorio
  CONSTRAINT clientes_razon_autonomo CHECK ( -- si autonomo, razon_social obligatoria
    tipo <> 'autonomo' OR (razon_social IS NOT NULL AND btrim(razon_social) <> '') -- vacio no vale si es autonomo
  ), -- fin check autonomo
  CONSTRAINT clientes_auth_fk -- liga el cliente con auth.users
    FOREIGN KEY (pk_cliente) REFERENCES auth.users (id) -- pk_cliente = id de auth
    ON DELETE CASCADE  -- si se borra el usuario de auth, se va el cliente
    ON UPDATE NO ACTION  -- el uuid de auth no se toca
);

CREATE TABLE categorias (
  pk_categoria varchar(40) PRIMARY KEY, -- numero de la categoria
  nom_categoria text NOT NULL UNIQUE, -- nombre del menu
  descripcion_categoria text -- texto corto
);

CREATE TABLE productos (
  pk_producto integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- numero unico del vestido
  fk_categoria varchar(40) NOT NULL, -- una sola categoria (pk de categorias)
  nombre_producto text NOT NULL, -- nombre del vestido, obligatorio
  url_imagen text, -- ruta de la foto
  descripcion_producto text, -- texto corto del producto
  precio numeric(10, 2) NOT NULL CHECK (precio > 0), -- precio, mayor que 0
  iva numeric(5, 2) NOT NULL DEFAULT 21, -- iva, por defecto 21
  descuento numeric(5, 2) NOT NULL DEFAULT 0 CHECK (descuento >= 0), -- descuento, no negativo
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0), -- unidades en tienda
  punto_reposicion integer NOT NULL DEFAULT 4, -- aviso cuando queda poco
  fecha_creacion timestamptz NOT NULL DEFAULT now(), -- alta, ahora por defecto
  fecha_baja timestamptz DEFAULT NULL, -- baja, vacio mientras este a la venta
  CONSTRAINT productos_categoria_fk -- liga el vestido con su categoria
    FOREIGN KEY (fk_categoria) REFERENCES categorias (pk_categoria)
    ON DELETE RESTRICT  -- no borro una categoría si todavía tiene vestidos
    ON UPDATE CASCADE   -- si cambia el código de categoría, los productos se van con ella
);

CREATE TABLE facturas (
  pk_factura integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- numero unico de la factura
  fk_cliente uuid NOT NULL, -- cliente que compra (pk de clientes)
  fecha_compra timestamptz NOT NULL DEFAULT now(), -- cuando Stripe confirma el pago
  stripe_payment_intent_id text NOT NULL UNIQUE, -- id de Stripe, obligatorio, no se puede repetir
  iva numeric(5, 2) NOT NULL DEFAULT 21, -- iva de toda la tienda, por defecto 21
  CONSTRAINT facturas_cliente_fk -- liga la factura con el cliente
    FOREIGN KEY (fk_cliente) REFERENCES clientes (pk_cliente)
    ON DELETE RESTRICT  -- si hay compra, el cliente no se puede borrar
    ON UPDATE CASCADE
);

CREATE TABLE detalle_factura (
  fk_factura integer NOT NULL, -- factura a la que pertenece la linea
  fk_producto integer NOT NULL, -- vestido vendido (pk de productos)
  cantidad integer NOT NULL CHECK (cantidad > 0), -- cuantas unidades, mas de 0
  precio_unitario numeric(10, 2) NOT NULL CHECK (precio_unitario > 0), -- precio de esa linea, obligatorio
  -- la consigna escribe (precio * cantidad); usamos precio_unitario de la misma fila
  -- porque Postgres solo permite columnas de esa fila (no de productos)
  precio_total numeric(10, 2) GENERATED ALWAYS AS (precio_unitario * cantidad) STORED, -- lo calcula Postgres, no se escribe a mano
  descuento numeric(5, 2) NOT NULL DEFAULT 0, -- descuento de la linea
  iva numeric(5, 2) NOT NULL DEFAULT 21, -- iva de la linea si aplica
  PRIMARY KEY (fk_factura, fk_producto), -- una linea = una factura + un vestido
  CONSTRAINT detalle_factura_fk -- liga la linea con su factura
    FOREIGN KEY (fk_factura) REFERENCES facturas (pk_factura)
    ON DELETE CASCADE  -- si anulo la factura, se van las líneas
    ON UPDATE CASCADE, -- si cambia el numero de factura, las lineas siguen
  CONSTRAINT detalle_producto_fk -- liga la linea con el vestido
    FOREIGN KEY (fk_producto) REFERENCES productos (pk_producto)
    ON DELETE RESTRICT  -- no quito un vestido que ya se ha vendido
    ON UPDATE CASCADE -- si cambia el numero del vestido, la linea se actualiza
);

